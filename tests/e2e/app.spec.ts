async function open(page: Page, url: string) {
  await page.goto(url)
  await expect(page.locator('[data-app-ready="true"]')).toBeVisible()
}
async function role(page: Page, name: string) {
  await page.getByRole('combobox', { name: 'Simular rol' }).click()
  await page.getByRole('option', { name, exact: true }).click()
}
async function tab(page: Page, name: string) { await page.getByRole('tab', { name, exact: true }).click() }
async function confirm(page: Page, reference?: string) {
  if (reference) await page.getByRole('dialog').getByRole('textbox').first().fill(reference)
  await page.getByRole('button', { name: 'Confirmar simulación', exact: true }).click()
}
async function portalConfirm(page: Page) {
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('checkbox', { name: /Entiendo que confirmo/ }).check()
  await dialog.getByRole('button', { name: 'Confirmar simulación' }).click()
}

