  await page.getByRole('combobox').first().click()
  await page.getByRole('option', { name: 'Datos fiscales', exact: true }).click()
  await page.locator('input[type="file"]').setInputFiles({ name: 'datos-fiscales-demo.pdf', mimeType: 'application/pdf', buffer: Buffer.from('MUESTRA FICTICIA PARA TEST; NO PDF REAL') })
